namespace TpsDungeon.Items
{
    /// <summary>
    /// 遠距離の武器種の撃ち方（弓・杖・投擲・召喚）。値はアセットに焼き込まれるので並べ替えず、足すときは末尾に。
    /// </summary>
    public enum RangedAttackKind
    {
        /// <summary>遠距離の武器ではない（近接や素手）。</summary>
        None = 0,

        /// <summary>照準の先へ矢をまっすぐ放つ（弓）。数で扇に増え、多重で遅れてもう一斉射。</summary>
        Bow = 1,

        /// <summary>照準が当たった地面へ上から矢を降らせ、その範囲に刻みでダメージを与え続ける（持続弓）。</summary>
        Rain = 2,

        /// <summary>照準に近い敵へ杖から雷を放ち、近くの敵へ次々と飛び移らせる（電撃）。数で飛び移る回数が増え、多重で遅れてもう一度放つ。</summary>
        Chain = 3,

        /// <summary>照準の向きの地面から、範囲に当たる物を手前から順に連ねて突き出す（範囲連置）。数で扇状に列が増え、持続時間で列が伸び、多重でもう一列。</summary>
        Line = 4,

        /// <summary>押している間、杖の先から前へ炎を吐き続ける（火炎放射器）。決まった時間吐いたら止まり、待ちのあとまた吐ける。</summary>
        Flame = 5,

        /// <summary>手に持った武器そのものを照準の先へまっすぐ投げる（投擲）。弓と同じく数で扇に増え、多重で遅れてもう一投。投げた物は武器ごとの速さで回る。</summary>
        Throw = 6,

        /// <summary>狙った地面に、敵を引きつける置物（おとり）を呼び出す（召喚）。数で狙った所の周りのランダムな所に増え、持続時間で長く居る。呼び直すと前の分は消える。</summary>
        Summon = 7,

        /// <summary>狙った地面へ種を投げ、落ちた所に治癒の場を張って中の味方を刻みで回復する（治癒持続）。数で付近に場が増え、多重で同じ所にもう一度張る。</summary>
        HealField = 8,
    }
}
